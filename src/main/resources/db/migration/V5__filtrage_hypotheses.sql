-- F4 : filtrage d'hypothèses (module « joueur »).
-- Une enquête = des variables ordonnées (suspect, lieu, objet...), chacune avec un domaine de valeurs,
-- et des indices, chaque indice étant une clause (disjonction de littéraux).
-- Compatible PostgreSQL et H2 (mode PostgreSQL).

CREATE TABLE joueur_enquete (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR(200) NOT NULL
);

-- « ordre » fixe l'ordre de parcours du retour arrière : il est unique et commence à 0.
CREATE TABLE joueur_variable (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquete_id BIGINT       NOT NULL REFERENCES joueur_enquete (id) ON DELETE CASCADE,
    code       VARCHAR(50)  NOT NULL,
    ordre      INT          NOT NULL CHECK (ordre >= 0),
    CONSTRAINT uq_joueur_variable_code  UNIQUE (enquete_id, code),
    CONSTRAINT uq_joueur_variable_ordre UNIQUE (enquete_id, ordre)
);

CREATE TABLE joueur_valeur_domaine (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variable_id BIGINT       NOT NULL REFERENCES joueur_variable (id) ON DELETE CASCADE,
    code        VARCHAR(100) NOT NULL,
    ordre       INT          NOT NULL CHECK (ordre >= 0),
    CONSTRAINT uq_joueur_valeur_code  UNIQUE (variable_id, code),
    CONSTRAINT uq_joueur_valeur_ordre UNIQUE (variable_id, ordre),
    -- nécessaire pour la clé étrangère composite de joueur_litteral
    CONSTRAINT uq_joueur_valeur_variable UNIQUE (id, variable_id)
);

CREATE TABLE joueur_indice (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquete_id BIGINT       NOT NULL REFERENCES joueur_enquete (id) ON DELETE CASCADE,
    libelle    VARCHAR(300) NOT NULL
);

-- Un littéral d'une clause : (variable, valeur, positif).
-- La clé composite (valeur_id, variable_id) interdit en base une valeur qui n'appartient pas
-- au domaine de la variable du littéral.
CREATE TABLE joueur_litteral (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indice_id   BIGINT  NOT NULL REFERENCES joueur_indice (id) ON DELETE CASCADE,
    variable_id BIGINT  NOT NULL REFERENCES joueur_variable (id),
    valeur_id   BIGINT  NOT NULL,
    positif     BOOLEAN NOT NULL,
    CONSTRAINT fk_joueur_litteral_valeur
        FOREIGN KEY (valeur_id, variable_id) REFERENCES joueur_valeur_domaine (id, variable_id)
);

CREATE INDEX idx_joueur_variable_enquete ON joueur_variable (enquete_id);
CREATE INDEX idx_joueur_indice_enquete   ON joueur_indice (enquete_id);
CREATE INDEX idx_joueur_litteral_indice  ON joueur_litteral (indice_id);
