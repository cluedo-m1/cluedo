CREATE TABLE batiment (
    code VARCHAR(20) PRIMARY KEY,
    nom  VARCHAR(120) NOT NULL
);

CREATE TABLE connexion (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depart  VARCHAR(20) NOT NULL,
    arrivee VARCHAR(20) NOT NULL,
    duree   INTEGER     NOT NULL,
    CONSTRAINT fk_connexion_depart
        FOREIGN KEY (depart) REFERENCES batiment (code),
    CONSTRAINT fk_connexion_arrivee
        FOREIGN KEY (arrivee) REFERENCES batiment (code),
    CONSTRAINT ck_connexion_duree
        CHECK (duree > 0),
    CONSTRAINT ck_connexion_boucle
        CHECK (depart <> arrivee),
    CONSTRAINT uk_connexion
        UNIQUE (depart, arrivee)
);